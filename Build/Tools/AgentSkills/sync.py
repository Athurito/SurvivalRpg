"""Mirror the shared agent skills into Claude Code and verify the agent instruction setup.

Canonical skills live in `.agents/skills/<name>/`, where Codex discovers them. Claude Code only
discovers `.claude/skills/<name>/`, so this tool writes a generated mirror of every skill there.
Full copies instead of pointer stubs let Claude load the real skill body on invocation and keep
references one level deep. Codex-only `agents/` metadata is not mirrored. Symlinks are avoided
because Windows clones check them out as plain text unless `core.symlinks` is enabled.

`--check` changes nothing and exits with 1 on:
- missing, stale, or extra files in a generated mirror, or a mirror without a canonical skill
- invalid skill frontmatter
- repository paths, `/Game/...` asset paths, or `URpg`/`ARpg`/`FRpg`/`ERpg`/`IRpg` identifiers
  named in the canonical skills, `AGENTS.md`, or `CLAUDE.md` that do not exist
- `$skill-name` references in that Markdown (Codex-only syntax)
- an `AGENTS.md` without a sibling `CLAUDE.md` that imports it with `@AGENTS.md`
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import shutil
import sys


REPO = Path(__file__).resolve().parents[3]
GENERATED_MARKER = "GENERATED by Build/Tools/AgentSkills/sync.py"
INSTRUCTION_FILES = ("AGENTS.md", "CLAUDE.md")
CODEX_ONLY = ("agents",)

NAME_PATTERN = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
MAX_NAME = 64
# Agent Skills spec limit; Claude Code allows 1536, so the stricter value keeps both tools valid.
MAX_DESCRIPTION = 1024
# Backticked or linked repository paths that must exist. Globs and placeholders are skipped.
PATH_PREFIXES = (".agents/", ".claude/", ".codex/", ".github/", "Build/", "Config/", "docs/", "Plugins/", "Source/")
CODE_SPAN = re.compile(r"`([^`\n]+)`")
MARKDOWN_LINK = re.compile(r"\]\(([^)\s#]+)(?:#[^)]*)?\)")
IDENTIFIER = re.compile(r"^[UAFEI]Rpg[A-Za-z0-9_]+$")
SOURCE_IDENTIFIER = re.compile(r"\b[UAFEI]Rpg[A-Za-z0-9_]+\b")
PLACEHOLDER = re.compile(r"[*<>{}]")
# Directories that never hold instruction files; skipping them keeps the AGENTS.md walk fast.
WALK_SKIP = {".git", ".vs", ".idea", "Binaries", "Content", "DerivedDataCache", "Intermediate", "Saved", "__pycache__"}


class SkillError(RuntimeError):
    pass


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def rel(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def canonical_root(root: Path) -> Path:
    return root / ".agents" / "skills"


def claude_root(root: Path) -> Path:
    return root / ".claude" / "skills"


def split_frontmatter(path: Path, text: str) -> tuple[str, str]:
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise SkillError(f"{path}: missing YAML frontmatter at the first line")
    return text[: match.end()], match.group(1)


def validate_skill(skill_file: Path) -> str:
    _, frontmatter = split_frontmatter(skill_file, read_text(skill_file))
    fields = {}
    for line in frontmatter.split("\n"):
        key, separator, value = line.partition(":")
        if separator and not line.startswith((" ", "\t")):
            fields[key.strip()] = value.strip()
    name = fields.get("name", "")
    description = fields.get("description", "")
    folder = skill_file.parent.name
    if name != folder:
        raise SkillError(f"{skill_file}: name '{name}' must match folder '{folder}'")
    if len(name) > MAX_NAME or not NAME_PATTERN.match(name) or "claude" in name or "anthropic" in name:
        raise SkillError(f"{skill_file}: name must be lowercase words joined by hyphens, at most {MAX_NAME} characters, without reserved words")
    if not description:
        raise SkillError(f"{skill_file}: description is required")
    if len(description) > MAX_DESCRIPTION:
        raise SkillError(f"{skill_file}: description has {len(description)} characters, limit {MAX_DESCRIPTION}")
    if not description.startswith(('"', "'")) and (": " in description or " #" in description):
        raise SkillError(f"{skill_file}: quote the description; ': ' or ' #' breaks a plain YAML scalar")
    return name


def discover(root: Path) -> list[str]:
    names = [validate_skill(path) for path in sorted(canonical_root(root).glob("*/SKILL.md"))]
    if not names:
        raise SkillError(f"no skills found under {canonical_root(root)}")
    return names


def canonical_files(root: Path, name: str) -> list[Path]:
    skill_dir = canonical_root(root) / name
    files = []
    for path in sorted(skill_dir.rglob("*")):
        relative = path.relative_to(skill_dir)
        if path.is_file() and relative.parts[0] not in CODEX_ONLY and "__pycache__" not in relative.parts:
            files.append(relative)
    return files


def mirror_content(root: Path, name: str, relative: Path) -> bytes:
    source = canonical_root(root) / name / relative
    if source.suffix != ".md":
        return source.read_bytes()
    text = read_text(source)
    marker = f"<!-- {GENERATED_MARKER} from {rel(root, source)}; edit the canonical file, then rerun the tool. -->\n\n"
    if relative.as_posix() == "SKILL.md":
        frontmatter, _ = split_frontmatter(source, text)
        text = frontmatter + "\n" + marker + text[len(frontmatter):].lstrip("\n")
    else:
        text = marker + text
    return text.encode("utf-8")


def is_generated(folder: Path) -> bool:
    skill = folder / "SKILL.md"
    return skill.is_file() and GENERATED_MARKER in read_text(skill)


def mirror_problems(root: Path, names: list[str]) -> list[str]:
    problems = []
    for name in names:
        target = claude_root(root) / name
        if target.is_dir() and not is_generated(target):
            raise SkillError(f"{rel(root, target)} exists without the generated marker; rename the Claude-only skill")
        expected = canonical_files(root, name)
        for relative in expected:
            path = target / relative
            if not path.is_file():
                problems.append(f"missing mirror file: {rel(root, path)}")
            elif path.read_bytes().replace(b"\r\n", b"\n") != mirror_content(root, name, relative):
                problems.append(f"stale mirror file: {rel(root, path)}")
        if target.is_dir():
            wanted = {relative.as_posix() for relative in expected}
            for path in sorted(target.rglob("*")):
                if path.is_file() and path.relative_to(target).as_posix() not in wanted:
                    problems.append(f"extra mirror file: {rel(root, path)}")
    if claude_root(root).is_dir():
        for folder in sorted(path for path in claude_root(root).iterdir() if path.is_dir()):
            if folder.name not in names and is_generated(folder):
                problems.append(f"orphaned mirror: {rel(root, folder)}")
    return problems


def write(root: Path, names: list[str]) -> None:
    for name in names:
        target = claude_root(root) / name
        if target.is_dir() and not is_generated(target):
            raise SkillError(f"{rel(root, target)} exists without the generated marker; rename the Claude-only skill")
        expected = canonical_files(root, name)
        for relative in expected:
            path = target / relative
            content = mirror_content(root, name, relative)
            if not path.is_file() or path.read_bytes().replace(b"\r\n", b"\n") != content:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content)
                print(f"wrote {rel(root, path)}")
        wanted = {relative.as_posix() for relative in expected}
        for path in sorted(target.rglob("*"), reverse=True):
            if path.is_file() and path.relative_to(target).as_posix() not in wanted:
                path.unlink()
                print(f"removed {rel(root, path)}")
            elif path.is_dir() and not any(path.iterdir()):
                path.rmdir()
    if claude_root(root).is_dir():
        for folder in sorted(path for path in claude_root(root).iterdir() if path.is_dir()):
            if folder.name not in names and is_generated(folder):
                shutil.rmtree(folder)
                print(f"removed orphaned {rel(root, folder)}")


def checked_documents(root: Path) -> list[Path]:
    documents = sorted(canonical_root(root).rglob("*.md"))
    return documents + [root / name for name in INSTRUCTION_FILES if (root / name).is_file()]


def source_identifiers(root: Path) -> set[str]:
    found: set[str] = set()
    source = root / "Source"
    if source.is_dir():
        for path in source.rglob("*"):
            if path.suffix in (".h", ".cpp", ".inl"):
                found.update(SOURCE_IDENTIFIER.findall(path.read_text(encoding="utf-8", errors="ignore")))
    return found


def span_problems(root: Path, label: str, text: str, identifiers: set[str]) -> list[str]:
    """Repository paths, `/Game/...` asset paths, and `URpg`-style identifiers in code spans must exist."""
    problems = []
    for span in sorted(set(CODE_SPAN.findall(text))):
        if PLACEHOLDER.search(span):
            continue
        if span.startswith(PATH_PREFIXES) and not (root / span.rstrip("/")).exists():
            problems.append(f"{label}: missing path {span}")
        elif span.startswith("/Game/"):
            package = root / "Content" / span[len("/Game/"):].split(".")[0].rstrip("/")
            if not (package.is_dir() or package.with_suffix(".uasset").is_file() or package.with_suffix(".umap").is_file()):
                problems.append(f"{label}: missing asset path {span}")
        elif IDENTIFIER.match(span) and span not in identifiers:
            problems.append(f"{label}: identifier {span} not found in Source/")
    return problems


def reference_problems(root: Path) -> list[str]:
    identifiers = source_identifiers(root)
    problems = []
    for document in checked_documents(root):
        text = read_text(document)
        problems += span_problems(root, rel(root, document), text, identifiers)
        for link in sorted(set(MARKDOWN_LINK.findall(text))):
            if "://" not in link and not PLACEHOLDER.search(link) and not (document.parent / link).exists():
                problems.append(f"{rel(root, document)}: broken link {link}")
    return problems


def neutrality_problems(root: Path, names: list[str]) -> list[str]:
    """Markdown names skills plainly; `$name` is Codex-only syntax (agents/openai.yaml may use it)."""
    pattern = re.compile(rf"\$({'|'.join(re.escape(name) for name in names)})\b")
    problems = []
    for document in checked_documents(root):
        for number, line in enumerate(read_text(document).split("\n"), start=1):
            for match in pattern.finditer(line):
                problems.append(f"{rel(root, document)}:{number}: use `{match.group(1)}` instead of ${match.group(1)}")
    return problems


def instruction_pairing_problems(root: Path) -> list[str]:
    """Claude Code reads CLAUDE.md files only once one exists, so every AGENTS.md needs an importing sibling."""
    problems = []
    for directory, subdirectories, files in os.walk(root):
        subdirectories[:] = [name for name in subdirectories if name not in WALK_SKIP]
        if "AGENTS.md" not in files:
            continue
        sibling = Path(directory) / "CLAUDE.md"
        if not sibling.is_file() or not re.search(r"^@AGENTS\.md\s*$", read_text(sibling), re.M):
            problems.append(f"{rel(root, Path(directory) / 'AGENTS.md')}: add a sibling CLAUDE.md starting with @AGENTS.md")
    return problems


def run(root: Path, check: bool) -> list[str]:
    names = discover(root)
    if not check:
        write(root, names)
    return (mirror_problems(root, names) + reference_problems(root)
            + neutrality_problems(root, names) + instruction_pairing_problems(root))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify only; exit 1 on any problem")
    args = parser.parse_args()
    try:
        problems = run(REPO, args.check)
    except SkillError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        return 1
    print("ok: agent skills and instruction files are consistent")
    return 0


if __name__ == "__main__":
    sys.exit(main())
