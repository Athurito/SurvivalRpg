"""Generate and verify the Claude Code entry points for the shared agent skills.

Canonical skills live in `.agents/skills/<name>/SKILL.md`; Codex discovers them there
natively. Claude Code only discovers `.claude/skills/<name>/SKILL.md`, so this tool
writes a small generated stub per skill that repeats the trigger metadata and points
to the canonical file. Symlinks are avoided because Windows clones check them out as
plain text unless `core.symlinks` is enabled.

`--check` changes nothing. It fails on stale or orphaned stubs, invalid frontmatter,
repository paths in the canonical skills or `AGENTS.md`/`CLAUDE.md` that do not
exist, and tool-specific `$skill-name` references in that Markdown.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import shutil
import sys


REPO = Path(__file__).resolve().parents[3]
CANONICAL_ROOT = REPO / ".agents" / "skills"
CLAUDE_ROOT = REPO / ".claude" / "skills"
GENERATED_MARKER = "GENERATED by Build/Tools/AgentSkills/sync.py"
INSTRUCTION_FILES = ("AGENTS.md", "CLAUDE.md")

NAME_PATTERN = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
MAX_NAME = 64
# Agent Skills spec limit; Claude Code allows 1536, so the stricter value keeps both tools valid.
MAX_DESCRIPTION = 1024
# Backticked or linked repository paths that must exist. Globs and placeholders are skipped.
PATH_PREFIXES = (".agents/", ".claude/", ".codex/", "Build/", "Config/", "docs/", "Plugins/", "Source/")
BACKTICK_PATH = re.compile(r"`([^`\s]+)`")
MARKDOWN_LINK = re.compile(r"\]\(([^)\s#]+)(?:#[^)]*)?\)")


class SkillError(RuntimeError):
    pass


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def parse_skill(skill_file: Path) -> dict[str, str]:
    text = read_text(skill_file)
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise SkillError(f"{skill_file}: missing YAML frontmatter at the first line")
    fields: dict[str, str] = {}
    raw_lines: dict[str, str] = {}
    for line in match.group(1).split("\n"):
        key, separator, value = line.partition(":")
        if separator and not line.startswith((" ", "\t")):
            fields[key.strip()] = value.strip()
            raw_lines[key.strip()] = line
    name = fields.get("name", "")
    description = fields.get("description", "")
    folder = skill_file.parent.name
    if name != folder:
        raise SkillError(f"{skill_file}: name '{name}' must match folder '{folder}'")
    if len(name) > MAX_NAME or not NAME_PATTERN.match(name):
        raise SkillError(f"{skill_file}: name must be lowercase words joined by hyphens, at most {MAX_NAME} characters")
    if not description:
        raise SkillError(f"{skill_file}: description is required")
    if len(description) > MAX_DESCRIPTION:
        raise SkillError(f"{skill_file}: description has {len(description)} characters, limit {MAX_DESCRIPTION}")
    if not description.startswith(('"', "'")) and (": " in description or " #" in description):
        raise SkillError(f"{skill_file}: quote the description; ': ' or ' #' breaks a plain YAML scalar")
    title = re.search(r"^# (.+)$", text[match.end():], re.M)
    return {
        "name": name,
        "name_line": raw_lines["name"],
        "description_line": raw_lines["description"],
        "title": title.group(1).strip() if title else name,
    }


def render_stub(skill: dict[str, str]) -> str:
    canonical = f".agents/skills/{skill['name']}"
    return (
        "---\n"
        f"{skill['name_line']}\n"
        f"{skill['description_line']}\n"
        "---\n"
        "\n"
        f"<!-- {GENERATED_MARKER} from {canonical}/SKILL.md. "
        "Edit the canonical skill, then rerun the tool. -->\n"
        "\n"
        f"# {skill['title']}\n"
        "\n"
        "Claude Code entry point for a skill shared with Codex. The canonical instructions live in\n"
        f"`{canonical}/SKILL.md`, relative to the repository root.\n"
        "\n"
        "1. Read that file completely before acting and follow it as this skill's instructions.\n"
        f"2. Resolve its relative links, such as `references/*.md`, against `{canonical}/`.\n"
        "3. Skills it names by their plain name are available here as `/<name>`.\n"
    )


def discover() -> list[dict[str, str]]:
    skills = [parse_skill(path) for path in sorted(CANONICAL_ROOT.glob("*/SKILL.md"))]
    if not skills:
        raise SkillError(f"no skills found under {CANONICAL_ROOT}")
    return skills


def is_generated_stub(folder: Path) -> bool:
    stub = folder / "SKILL.md"
    entries = [entry.name for entry in folder.iterdir()]
    return entries == ["SKILL.md"] and GENERATED_MARKER in read_text(stub)


def stub_problems(skills: list[dict[str, str]]) -> list[str]:
    problems = []
    expected = {skill["name"] for skill in skills}
    for skill in skills:
        stub = CLAUDE_ROOT / skill["name"] / "SKILL.md"
        if not stub.is_file():
            problems.append(f"missing stub: {stub.relative_to(REPO).as_posix()}")
        elif read_text(stub) != render_stub(skill):
            problems.append(f"stale stub: {stub.relative_to(REPO).as_posix()}")
    if CLAUDE_ROOT.is_dir():
        for folder in sorted(path for path in CLAUDE_ROOT.iterdir() if path.is_dir()):
            if folder.name not in expected and (folder / "SKILL.md").is_file() and is_generated_stub(folder):
                problems.append(f"orphaned stub: {folder.relative_to(REPO).as_posix()}")
    return problems


def referenced_paths(document: Path) -> set[str]:
    text = read_text(document)
    found = set()
    for candidate in BACKTICK_PATH.findall(text):
        if candidate.startswith(PATH_PREFIXES):
            found.add(candidate)
    for link in MARKDOWN_LINK.findall(text):
        if "://" not in link:
            found.add(link)
    return found


def path_problems() -> list[str]:
    documents = sorted(CANONICAL_ROOT.rglob("*.md")) + [REPO / name for name in INSTRUCTION_FILES if (REPO / name).is_file()]
    problems = []
    for document in documents:
        for reference in sorted(referenced_paths(document)):
            if any(token in reference for token in ("*", "<", ">", "{", "}")):
                continue
            base = REPO if reference.startswith(PATH_PREFIXES) else document.parent
            if not (base / reference.rstrip("/")).exists():
                problems.append(f"{document.relative_to(REPO).as_posix()}: missing path {reference}")
    return problems


def neutrality_problems(skills: list[dict[str, str]]) -> list[str]:
    """Markdown must name skills plainly; `$name` is Codex-only syntax (agents/openai.yaml may use it)."""
    names = "|".join(re.escape(skill["name"]) for skill in skills)
    pattern = re.compile(rf"\$({names})\b")
    documents = sorted(CANONICAL_ROOT.rglob("*.md")) + [REPO / name for name in INSTRUCTION_FILES if (REPO / name).is_file()]
    problems = []
    for document in documents:
        for number, line in enumerate(read_text(document).split("\n"), start=1):
            for match in pattern.finditer(line):
                problems.append(f"{document.relative_to(REPO).as_posix()}:{number}: use `{match.group(1)}` instead of ${match.group(1)}")
    return problems


def write(skills: list[dict[str, str]]) -> None:
    expected = {skill["name"] for skill in skills}
    for skill in skills:
        stub = CLAUDE_ROOT / skill["name"] / "SKILL.md"
        stub.parent.mkdir(parents=True, exist_ok=True)
        content = render_stub(skill)
        if not stub.is_file() or read_text(stub) != content:
            stub.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {stub.relative_to(REPO).as_posix()}")
    if CLAUDE_ROOT.is_dir():
        for folder in sorted(path for path in CLAUDE_ROOT.iterdir() if path.is_dir()):
            if folder.name not in expected and (folder / "SKILL.md").is_file() and is_generated_stub(folder):
                shutil.rmtree(folder)
                print(f"removed orphaned {folder.relative_to(REPO).as_posix()}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify only; exit 1 on any problem")
    args = parser.parse_args()
    try:
        skills = discover()
        if not args.check:
            write(skills)
        problems = stub_problems(skills) + path_problems() + neutrality_problems(skills)
    except SkillError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        return 1
    print(f"ok: {len(skills)} skills in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
